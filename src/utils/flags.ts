const FALLBACK = "1d4e9e ffffff d42a35";
// Large-text contrast: names on stamps are bold and the outline is a shape
const MIN_CONTRAST = 3;

export interface StampColours {
	ground: string;
	figure: string;
	band: string;
}

export function luminance(hex: string) {
	const digits = hex.replace("#", "");
	const [r, g, b] = [0, 2, 4].map((i) => {
		const c = Number.parseInt(digits.slice(i, i + 2), 16) / 255;
		return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
	});
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a: string, b: string) {
	const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
	return (hi + 0.05) / (lo + 0.05);
}

// The figure (outline and name) is the flag colour that stands out most on the
// ground; the band is the next colour, so most stamps carry three of the flag's
export function stampColours(code: CountryCode): StampColours {
	const [ground, ...rest] = (PALETTES[code] ?? FALLBACK).split(" ");
	const best = rest.reduce((top, c) =>
		contrast(c, ground) > contrast(top, ground) ? c : top,
	);
	// Some flags have no strong pair (Kazakhstan's gold on sky blue)
	const figure =
		contrast(best, ground) >= MIN_CONTRAST
			? best
			: contrast("ffffff", ground) > contrast("1a1a1a", ground)
				? "ffffff"
				: "1a1a1a";
	const band = rest.find((c) => c !== figure) ?? figure;
	return { ground: `#${ground}`, figure: `#${figure}`, band: `#${band}` };
}
